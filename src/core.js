import { createHash } from 'node:crypto';

const asText = (value) => {
  if (value === null || value === undefined) return '';
  return typeof value === 'string' ? value : JSON.stringify(value);
};

const scoreValue = (trace) => {
  if (typeof trace.feedback === 'number') return trace.feedback;
  if (typeof trace.score === 'number') return trace.score;
  const scores = Array.isArray(trace.scores) ? trace.scores : Object.values(trace.scores || {});
  const numeric = scores.map((item) => typeof item === 'number' ? item : item?.value).filter(Number.isFinite);
  return numeric.length ? numeric.reduce((sum, value) => sum + value, 0) / numeric.length : null;
};

export function normalizeTraces(payload) {
  const source = Array.isArray(payload) ? payload : payload?.data || payload?.traces || [];
  if (!Array.isArray(source)) throw new Error('Expected an array, `data`, or `traces` field.');
  return source.map((trace, index) => ({
    id: String(trace.id || trace.trace_id || trace.run_id || index + 1),
    input: asText(trace.input ?? trace.inputs ?? trace.request ?? trace.prompt),
    output: asText(trace.output ?? trace.outputs ?? trace.response ?? trace.result),
    feedback: scoreValue(trace),
    error: asText(trace.error ?? (trace.status === 'error' ? 'trace status is error' : '')),
    latencyMs: Number(trace.latencyMs ?? trace.latency_ms ?? trace.latency ?? 0) || null,
    costUsd: Number(trace.costUsd ?? trace.cost_usd ?? trace.cost ?? 0) || null,
    metadata: trace.metadata || {},
  })).filter((trace) => trace.input || trace.output || trace.error);
}

function fingerprint(trace) {
  return createHash('sha256').update(`${trace.input}\n${trace.output}\n${trace.error}`).digest('hex').slice(0, 12);
}

export function mineCandidates(traces, { threshold = 0.5 } = {}) {
  const candidates = new Map();
  for (const trace of traces) {
    const reasons = [];
    if (trace.error) reasons.push('execution error');
    if (trace.feedback !== null && trace.feedback < threshold) reasons.push(`low feedback score (${trace.feedback})`);
    if (!trace.output && !trace.error) reasons.push('empty output');
    if (!reasons.length) continue;
    const key = fingerprint(trace);
    const existing = candidates.get(key);
    const candidate = {
      id: `t2t-${key}`,
      input: trace.input,
      observedOutput: trace.output,
      reason: reasons.join('; '),
      severity: trace.error ? 'high' : trace.feedback !== null && trace.feedback < 0 ? 'high' : 'medium',
      sourceTraceIds: [...(existing?.sourceTraceIds || []), trace.id],
      suggestedAssertions: trace.error
        ? ['must not error', 'returns a valid response']
        : ['meets task rubric', 'does not repeat the observed failure'],
    };
    candidates.set(key, candidate);
  }
  return [...candidates.values()];
}

export function analyseStability(samples, { passThreshold = 0.8 } = {}) {
  if (!Array.isArray(samples) || !samples.length) throw new Error('Stability input must contain at least one sample.');
  const grouped = new Map();
  for (const sample of samples) {
    const key = String(sample.testId || sample.id || 'default');
    const record = grouped.get(key) || { testId: key, runs: 0, passed: 0, errors: 0, scores: [] };
    record.runs += 1;
    if (sample.error) record.errors += 1;
    if (sample.passed === true) record.passed += 1;
    if (Number.isFinite(sample.score)) record.scores.push(sample.score);
    grouped.set(key, record);
  }
  return [...grouped.values()].map((record) => {
    const passRate = record.passed / record.runs;
    const meanScore = record.scores.length ? record.scores.reduce((a, b) => a + b, 0) / record.scores.length : null;
    const variance = record.scores.length ? record.scores.reduce((sum, score) => sum + (score - meanScore) ** 2, 0) / record.scores.length : null;
    const verdict = record.errors ? 'error' : passRate >= passThreshold && record.passed === record.runs ? 'stable_pass' : passRate >= passThreshold ? 'flaky' : passRate === 0 ? 'stable_fail' : 'flaky';
    return { ...record, passRate: Number(passRate.toFixed(3)), meanScore: meanScore === null ? null : Number(meanScore.toFixed(3)), stddev: variance === null ? null : Number(Math.sqrt(variance).toFixed(3)), verdict };
  });
}

function yamlQuote(value) { return JSON.stringify(String(value)); }

export function toPromptfoo(candidates) {
  const tests = candidates.map((candidate) => [
    '  - vars:',
    `      input: ${yamlQuote(candidate.input)}`,
    `    description: ${yamlQuote(`${candidate.id}: ${candidate.reason}`)}`,
    '    assert:',
    ...candidate.suggestedAssertions.map((assertion) => `      - type: llm-rubric\n        value: ${yamlQuote(assertion)}`),
  ].join('\n')).join('\n');
  return `# Generated by Trace2Test. Review every candidate before committing.\ndescription: Production failures promoted to regression candidates\nprompts:\n  - "{{input}}"\ntests:\n${tests || '  []'}\n`;
}

export function markdownReport(candidates, stability = []) {
  const rows = candidates.map((candidate) => `| ${candidate.id} | ${candidate.severity} | ${candidate.reason} | ${candidate.sourceTraceIds.join(', ')} |`).join('\n') || '| — | — | No failures promoted | — |';
  const stabilityRows = stability.map((record) => `| ${record.testId} | ${record.runs} | ${record.passRate} | ${record.stddev ?? '—'} | ${record.verdict} |`).join('\n') || '| — | — | — | — | No samples |';
  return `# Trace2Test report\n\n## Regression candidates\n\n| Candidate | Severity | Reason | Source traces |\n| --- | --- | --- | --- |\n${rows}\n\n## Stability\n\n| Test | Runs | Pass rate | Score stddev | Verdict |\n| --- | --- | --- | --- | --- |\n${stabilityRows}\n\n> Generated candidates are review inputs, not ground truth. Confirm the expected behavior before turning a candidate into a release gate.\n`;
}
